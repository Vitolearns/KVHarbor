#!/usr/bin/env python3
"""Render the README architecture diagram in both languages and themes."""

from argparse import ArgumentParser
from pathlib import Path
import re
import subprocess


ASSETS = Path(__file__).resolve().parents[1] / "assets" / "readme"
CHINESE = {
    "HTTP API": "HTTP 接口",
    "C++20 request scheduler": "C++20 请求调度",
    "Queues · Workers · Cancellation": "任务队列 · 工作名额 · 取消请求",
    "Text generation": "文本生成",
    "GPU · Text queue": "GPU · 文本队列",
    "llama.cpp or": "llama.cpp 或",
    "SSE text stream": "SSE 文本流",
    "Speech": "语音服务",
    "CPU · Separate task queues": "CPU · 转写与合成各有队列",
}
DARK = {
    "#17283a": "#e6eff5",
    "#fcfdff": "#152335",
    "#c7d7e3": "#4c6578",
    "#56798e": "#9ab3c4",
    "#eaf1f7": "#1b2d43",
    "#235d8d": "#a0ccf2",
    "#edf6fc": "#172f47",
    "#285e57": "#a0d8c4",
    "#eaf6f2": "#183734",
}
BOLD = {
    "HTTP API", "C++20 request scheduler", "Text generation",
    "Speech", "SSE text stream",
}
ACCENTS = {"GPU · Text queue": "#235d8d", "CPU · Separate task queues": "#285e57"}


def render(layout, translations, palette, title):
    def style_text(match):
        attributes, label = match.groups()
        attributes = attributes.replace('font-family="DejaVu Sans"', 'font-family="system-ui, sans-serif"')
        if label in BOLD:
            attributes += ' font-weight="700"'
        if label in ACCENTS:
            attributes = attributes.replace("#17283a", ACCENTS[label])
        return f"<text{attributes}>{translations.get(label, label)}</text>"

    svg = re.sub(r"<text([^>]*)>([^<]*)</text>", style_text, layout)
    for original, replacement in palette.items():
        svg = svg.replace(original, replacement)
    return svg.replace("<title>architecture</title>", f"<title>{title}</title>", 1)


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in SVGs differ")
    args = parser.parse_args()
    layout = subprocess.run(
        ["dot", "-Tsvg", str(ASSETS / "architecture.dot")], text=True,
        encoding="utf-8", capture_output=True, check=True,
    ).stdout
    # Lay out the graph once so Chinese labels work without local CJK fonts.
    layout = re.sub(r"<!-- Generated by graphviz version [^\n]*\n -->\n", "", layout)
    for suffix, translations, title in (
        ("", {}, "KVHarbor serving architecture"),
        ("-zh", CHINESE, "KVHarbor 服务架构"),
    ):
        for theme, palette in (("light", {}), ("dark", DARK)):
            path = ASSETS / f"architecture{suffix}-{theme}.svg"
            svg = render(layout, translations, palette, title)
            if args.check:
                if not path.is_file() or path.read_text(encoding="utf-8") != svg:
                    parser.exit(1, f"Regenerate {path.name}\n")
            else:
                path.write_text(svg, encoding="utf-8")


if __name__ == "__main__":
    main()
